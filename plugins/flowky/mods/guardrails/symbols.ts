// Which files hold reusable definitions, and which definitions a piece of code makes.
//
// Lexical, line by line, no parser and no dependency. Only TOP-LEVEL definitions count: the
// patterns are anchored at column 0, so methods, nested functions and indented blocks are never
// definitions here. Languages and what counts (spec 6.1, extended where noted):
//   TypeScript / JavaScript (.ts .tsx .mts .cts .js .jsx .mjs .cjs):
//     [export] [default] [async] function name, [export] [default] [abstract] class name,
//     export const|let name = (...) => / async (...) => / function / x =>.
//     Reusable (can be imported elsewhere): only the exported ones.
//   Python (.py): column-0 def, async def and class. Reusable: names not starting with "_".
//   Go (.go): func Name( and func Name[T any]( (never methods, func (r T) Name).
//     Reusable: capitalised names (Go exports by case).
//   Rust (.rs): pub [(crate)] [async] [unsafe] [const] fn, pub struct, pub enum, pub trait
//     (enum and trait added). Reusable: all of them (only pub items are indexed).
// Other languages are not indexed. Known limits: a definition written across several lines before
// its name, a definition produced by a macro or a decorator factory, and CommonJS
// `module.exports = { name }` exports are not seen (no report: a missed duplicate, never a false one).

import { posix } from './text'

export type Lang = 'js' | 'py' | 'go' | 'rs'
export type Kind = 'function' | 'class' | 'struct' | 'enum' | 'trait'
export type Definition = { name: string; kind: Kind; line: number; exported: boolean; signature: string }

const EXT_LANG: Record<string, Lang> = {
  ts: 'js', tsx: 'js', mts: 'js', cts: 'js', js: 'js', jsx: 'js', mjs: 'js', cjs: 'js',
  py: 'py', go: 'go', rs: 'rs',
}

export const LANGUAGE_NAMES: Record<Lang, string> = { js: 'TypeScript/JavaScript', py: 'Python', go: 'Go', rs: 'Rust' }

export function languageOf(path: string): Lang | undefined {
  const name = posix(path).split('/').pop() ?? ''
  if (/\.d\.[cm]?ts$/i.test(name)) return undefined
  const i = name.lastIndexOf('.')
  return i > 0 ? EXT_LANG[name.slice(i + 1).toLowerCase()] : undefined
}

/** Folders that hold dependencies, build output, generated or tool state: never indexed, never guarded. */
export const EXCLUDED_DIRS = new Set([
  'node_modules', 'vendor', 'third_party', 'third-party', 'dist', 'build', 'out', '.next', '.nuxt', '.svelte-kit',
  'coverage', '.flowky', '.claude', '.git', 'target', '__pycache__', '.venv', 'venv', '.tox', '.turbo', '.cache',
  'bower_components', 'Pods', 'generated', '__generated__', '.output', '.vercel',
])

/** Test folders and file names: their helpers are duplicated on purpose. */
const TEST_DIRS = new Set(['__tests__', '__mocks__', 'tests', 'test', 'spec', 'e2e', 'fixtures', 'testdata', '__fixtures__'])
const TEST_FILE = /(\.|_|-)(test|spec)\.[^.]+$|^test_[^/]+\.py$|_test\.(go|py)$|^conftest\.py$/i
/** Generated by name. */
const GENERATED_FILE = /\.generated\.[^.]+$|\.gen\.[^.]+$|\.pb\.go$|_pb2(_grpc)?\.py$|\.min\.[cm]?js$|\.bundle\.[cm]?js$/i
/** Generated by a marker in the first lines. */
const GENERATED_MARKER = /@generated|DO NOT EDIT|auto-generated|autogenerated|generated by|Code generated .* DO NOT EDIT/i

export type FileClass = 'source' | 'test' | 'generated' | 'excluded' | 'unsupported'

/** What a project-relative path is, by its name alone. */
export function classifyPath(rel: string): FileClass {
  const parts = posix(rel).split('/')
  const name = parts[parts.length - 1] ?? ''
  for (const dir of parts.slice(0, -1)) {
    if (EXCLUDED_DIRS.has(dir)) return 'excluded'
    if (TEST_DIRS.has(dir)) return 'test'
  }
  if (!languageOf(name)) return 'unsupported'
  if (TEST_FILE.test(name)) return 'test'
  if (GENERATED_FILE.test(name)) return 'generated'
  return 'source'
}

export const MAX_SOURCE_BYTES = 1024 * 1024

/** Whether file text is generated or minified (a marker in the first 5 lines, or very long lines). */
export function looksGenerated(text: string): boolean {
  const head = text.slice(0, 4096).split('\n').slice(0, 5).join('\n')
  if (GENERATED_MARKER.test(head)) return true
  const sample = text.slice(0, 65536)
  const lines = sample.split('\n')
  if (lines.some(l => l.length > 2000)) return true
  return sample.length > 4096 && sample.length / Math.max(1, lines.length) > 300
}

type Pattern = { re: RegExp; kind: Kind; exported: (m: RegExpExecArray, name: string) => boolean }

const PATTERNS: Record<Lang, Pattern[]> = {
  js: [
    { re: /^(export\s+)?(?:default\s+)?(?:declare\s+)?(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*[<(]/, kind: 'function', exported: m => Boolean(m[1]) },
    { re: /^(export\s+)?(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?class\s+([A-Za-z_$][\w$]*)\b/, kind: 'class', exported: m => Boolean(m[1]) },
    { re: /^(export\s+)(?:const|let)\s+([A-Za-z_$][\w$]*)\s*(?::[^=]{1,200})?=\s*(?:async\s+)?(?:\(|function\b|[A-Za-z_$][\w$]*\s*=>|<)/, kind: 'function', exported: () => true },
  ],
  py: [
    { re: /^()(?:async\s+)?def\s+([A-Za-z_]\w*)\s*\(/, kind: 'function', exported: (_m, n) => !n.startsWith('_') },
    { re: /^()class\s+([A-Za-z_]\w*)\s*[(:]/, kind: 'class', exported: (_m, n) => !n.startsWith('_') },
  ],
  go: [{ re: /^()func\s+([A-Za-z_]\w*)\s*[[(]/, kind: 'function', exported: (_m, n) => /^[A-Z]/.test(n) }],
  rs: [
    { re: /^(pub(?:\s*\((?:crate|super)\))?\s+)(?:const\s+)?(?:async\s+)?(?:unsafe\s+)?(?:extern\s+"[^"]*"\s+)?fn\s+([A-Za-z_]\w*)/, kind: 'function', exported: () => true },
    { re: /^(pub(?:\s*\((?:crate|super)\))?\s+)struct\s+([A-Za-z_]\w*)/, kind: 'struct', exported: () => true },
    { re: /^(pub(?:\s*\((?:crate|super)\))?\s+)enum\s+([A-Za-z_]\w*)/, kind: 'enum', exported: () => true },
    { re: /^(pub(?:\s*\((?:crate|super)\))?\s+)(?:unsafe\s+)?trait\s+([A-Za-z_]\w*)/, kind: 'trait', exported: () => true },
  ],
}

/** Lines inside Python triple-quoted strings and JS block comments are skipped (best effort). */
function codeLines(text: string, lang: Lang): { line: string; n: number }[] {
  const out: { line: string; n: number }[] = []
  const lines = text.split('\n')
  let inBlock = false
  for (let i = 0; i < lines.length && i < 200_000; i++) {
    const raw = lines[i]!.replace(/\r$/, '')
    if (lang === 'py') {
      const quotes = (raw.match(/"""|'''/g) ?? []).length
      if (inBlock) {
        if (quotes % 2 === 1) inBlock = false
        continue
      }
      if (quotes % 2 === 1) {
        inBlock = true
        continue
      }
    } else {
      if (inBlock) {
        if (raw.includes('*/')) inBlock = false
        continue
      }
      if (/^\s*\/\*/.test(raw) && !raw.includes('*/')) {
        inBlock = true
        continue
      }
    }
    if (raw.length > 2000) continue
    out.push({ line: raw, n: i + 1 })
  }
  return out
}

/** The top-level definitions a text makes, in order; a name defined twice (overloads) keeps its first line. */
export function definitions(text: string | undefined, lang: Lang | undefined): Definition[] {
  if (!text || !lang) return []
  const out: Definition[] = []
  const seen = new Set<string>()
  for (const { line, n } of codeLines(text, lang)) {
    if (!line || line[0] === ' ' || line[0] === '\t') continue
    for (const p of PATTERNS[lang]) {
      const m = p.re.exec(line)
      if (!m) continue
      const name = m[2]!
      if (!seen.has(name)) {
        seen.add(name)
        out.push({ name, kind: p.kind, line: n, exported: p.exported(m, name), signature: line.trim().slice(0, 200) })
      }
      break
    }
  }
  return out
}

/** Just the names. */
export function definedNames(text: string | undefined, lang: Lang | undefined): Set<string> {
  return new Set(definitions(text, lang).map(d => d.name))
}
